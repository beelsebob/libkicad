std::string _utf8(const fs::path& path) {
    const std::u8string text = path.u8string();
    return std::string(text.begin(), text.end());
}

fs::path _fromUtf8(const std::string& text) {
    return fs::path(std::u8string(text.begin(), text.end()));
}

std::optional<std::string> _environment(const char* name) {
    const char* value = std::getenv(name);
    if (value == nullptr || value[0] == '\0') return std::nullopt;
    return std::string(value);
}

bool _isFile(const fs::path& path) {
    std::error_code error;
    return fs::is_regular_file(path, error);
}

/// The first `name` on PATH, if any.
std::optional<fs::path> _onPath(const std::string& name) {
    const std::optional<std::string> path = _environment("PATH");
    if (!path) return std::nullopt;
#if defined(_WIN32)
    const char separator = ';';
#else
    const char separator = ':';
#endif
    std::stringstream stream(*path);
    std::string directory;
    while (std::getline(stream, directory, separator)) {
        if (!directory.empty() && _isFile(_fromUtf8(directory) / name)) return _fromUtf8(directory) / name;
    }
    return std::nullopt;
}

/// The installed KiCad's Python (with KiCad's pcbnew module) and kicad-cli. LIBKICAD_KICAD_PYTHON
/// and LIBKICAD_KICAD_CLI override the platform's standard install locations.
bool _findKicad(RuntimeState& runtime, std::string& error) {
    if (auto python = _environment("LIBKICAD_KICAD_PYTHON")) runtime.python = _fromUtf8(*python);
    if (auto cli = _environment("LIBKICAD_KICAD_CLI")) runtime.kicadCli = _fromUtf8(*cli);

#if defined(_WIN32)
    // C:\Program Files\KiCad\<version>\bin, newest version first.
    if (runtime.python.empty() || runtime.kicadCli.empty()) {
        const fs::path root = _fromUtf8(_environment("ProgramFiles").value_or("C:\\Program Files")) / "KiCad";
        std::vector<std::pair<std::vector<int>, fs::path>> installs;
        std::error_code ignored;
        for (const fs::directory_entry& entry : fs::directory_iterator(root, ignored)) {
            const fs::path bin = entry.path() / "bin";
            if (!_isFile(bin / "python.exe") || !_isFile(bin / "kicad-cli.exe")) continue;
            std::vector<int> version;
            std::stringstream parts(_utf8(entry.path().filename()));
            std::string part;
            while (std::getline(parts, part, '.')) version.push_back(std::atoi(part.c_str()));
            installs.emplace_back(std::move(version), bin);
        }
        std::sort(installs.begin(), installs.end(), [](const auto& a, const auto& b) { return a.first > b.first; });
        if (!installs.empty()) {
            if (runtime.python.empty()) runtime.python = installs.front().second / "python.exe";
            if (runtime.kicadCli.empty()) runtime.kicadCli = installs.front().second / "kicad-cli.exe";
        }
    }
#elif defined(__APPLE__)
    const fs::path app = "/Applications/KiCad/KiCad.app/Contents";
    if (runtime.python.empty()) runtime.python = app / "Frameworks/Python.framework/Versions/Current/bin/python3";
    if (runtime.kicadCli.empty()) runtime.kicadCli = app / "MacOS/kicad-cli";
#else
    // Distribution packages install KiCad's pcbnew module for the system Python.
    if (runtime.python.empty()) runtime.python = _onPath("python3").value_or(fs::path("/usr/bin/python3"));
    if (runtime.kicadCli.empty()) runtime.kicadCli = _onPath("kicad-cli").value_or(fs::path("/usr/bin/kicad-cli"));
#endif

    if (!_isFile(runtime.python)) {
        error = "No installed KiCad was found (looked for its Python at \"" + _utf8(runtime.python) +
                "\"). Install KiCad, or set LIBKICAD_KICAD_PYTHON to the Python that has KiCad's pcbnew module.";
        return false;
    }
    return true;
}

/// Runs the bridge, returning its "result", or nullopt with `error` set.
std::optional<json> _bridge(RuntimeState& runtime, std::vector<std::string> arguments, std::string& error) {
    const fs::path output = runtime.workDirectory / ("result-" + std::to_string(++runtime.counter) + ".json");
    arguments.insert(arguments.begin(), _utf8(runtime.script));
    arguments.push_back("--kicad-cli");
    arguments.push_back(_utf8(runtime.kicadCli));
    arguments.push_back("--output");
    arguments.push_back(_utf8(output));

    std::string launchError;
    const int status = runProcess(runtime.python, arguments, launchError);
    if (status < 0) {
        error = launchError;
        return std::nullopt;
    }
    json reply;
    {
        std::ifstream stream(output, std::ios::binary);
        if (!stream) {
            error = "KiCad's Python (\"" + _utf8(runtime.python) + "\") could not run libkicad's KiCad bridge (exit status " +
                    std::to_string(status) + "). Check that it can import KiCad's pcbnew module.";
            return std::nullopt;
        }
        try {
            stream >> reply;
        } catch (const json::exception& exception) {
            error = std::string("libkicad's KiCad bridge returned malformed JSON: ") + exception.what();
            return std::nullopt;
        }
    }
    std::error_code ignored;
    fs::remove(output, ignored);
    if (!reply.value("ok", false)) {
        error = reply.value("error", std::string("libkicad's KiCad bridge failed"));
        return std::nullopt;
    }
    if (reply.value("protocol", 0) != 1) {
        error = "libkicad's KiCad bridge speaks an unexpected protocol version";
        return std::nullopt;
    }
    return std::move(reply["result"]);
}

std::optional<std::string> _unreadableFileError(const std::string& path, const char* description) {
    if (path.empty()) return std::string("No ") + description + " file was specified";
    std::error_code statusError;
    const fs::file_status status = fs::status(_fromUtf8(path), statusError);
    if (statusError || !fs::exists(status)) {
        if (!statusError || statusError == std::errc::no_such_file_or_directory) {
            return "The KiCad " + std::string(description) + " file does not exist: \"" + path + "\"";
        }
        return "Cannot access the KiCad " + std::string(description) + " file \"" + path + "\": " + statusError.message();
    }
    if (!fs::is_regular_file(status)) {
        return "The KiCad " + std::string(description) + " path is not a regular file: \"" + path + "\"";
    }
    std::ifstream stream(_fromUtf8(path), std::ios::binary);
    if (!stream.is_open()) {
        return "Cannot read the KiCad " + std::string(description) + " file \"" + path +
               "\": permission denied or the file is unavailable";
    }
    return std::nullopt;
}

/// Drops cached answers when the board or project file changed since they were computed. Must
/// hold state.mutex. False, with `error` set, if either file can't be read.
bool _refresh(BoardState& state, std::string& error) {
    if (auto problem = _unreadableFileError(state.projectPath, "project")) {
        error = *problem;
        return false;
    }
    if (auto problem = _unreadableFileError(state.boardPath, "board")) {
        error = *problem;
        return false;
    }
    std::error_code projectError, boardError;
    const auto projectMTime = fs::last_write_time(_fromUtf8(state.projectPath), projectError);
    const auto boardMTime = fs::last_write_time(_fromUtf8(state.boardPath), boardError);
    if (projectError || boardError || projectMTime != state.projectMTime || boardMTime != state.boardMTime) {
        state.summary.reset();
        state.geometry.reset();
        state.layers.clear();
        state.projectMTime = projectMTime;
        state.boardMTime = boardMTime;
    }
    return true;
}

std::vector<std::string> _boardArguments(const BoardState& state, const char* query) {
    return {query, "--board", state.boardPath, "--project", state.projectPath};
}

/// The bridge's "board" answer: everything but whole-board geometry.
const json* _summary(BoardState& state, std::string& error) {
    if (!_refresh(state, error)) return nullptr;
    if (!state.summary) {
        std::optional<json> result = _bridge(state.runtime, _boardArguments(state, "board"), error);
        if (!result) return nullptr;
        state.summary = std::move(*result);
    }
    return &*state.summary;
}

PolygonLoop _loop(const json& entry) {
    // [hole, [x0, y0, x1, y1, ...]]
    PolygonLoop loop;
    loop.hole = entry.at(0).get<int>() != 0;
    const json& points = entry.at(1);
    loop.pointsMm.reserve(points.size() / 2);
    for (std::size_t i = 0; i + 1 < points.size(); i += 2) {
        loop.pointsMm.emplace_back(points[i].get<double>(), points[i + 1].get<double>());
    }
    return loop;
}

std::vector<PolygonLoop> _loops(const json& entries) {
    std::vector<PolygonLoop> loops;
    loops.reserve(entries.size());
    for (const json& entry : entries) loops.push_back(_loop(entry));
    return loops;
}

std::vector<CopperPolygon> _copper(const json& entries) {
    // [net, layer, zone, footprintRef, padNumber, hole, points]
    std::vector<CopperPolygon> copper;
    copper.reserve(entries.size());
    for (const json& entry : entries) {
        CopperPolygon polygon;
        polygon.netName = entry.at(0).get<std::string>();
        polygon.copperLayerName = entry.at(1).get<std::string>();
        polygon.zone = entry.at(2).get<int>() != 0;
        polygon.footprintRef = entry.at(3).get<std::string>();
        polygon.padNumber = entry.at(4).get<std::string>();
        polygon.loop = _loop(json::array({entry.at(5), entry.at(6)}));
        copper.push_back(std::move(polygon));
    }
    return copper;
}

BoardLayerInfo _layerInfo(const json& entry) {
    return BoardLayerInfo{entry.at(0).get<std::string>(), entry.at(1).get<bool>(), entry.at(2).get<bool>()};
}

PadPosition _padPosition(const json& pad, const std::string& footprintRef) {
    PadPosition position;
    position.footprintRef = footprintRef;
    position.padNumber = pad.at("num").get<std::string>();
    position.netName = pad.at("net").get<std::string>();
    position.pinType = pad.at("type").get<std::string>();
    position.xMm = pad.at("x").get<double>();
    position.yMm = pad.at("y").get<double>();
    position.orientationDeg = pad.at("rot").get<double>();
    position.copperLayerName = pad.at("layer").get<std::string>();
    position.widthMm = pad.at("w").get<double>();
    position.heightMm = pad.at("h").get<double>();
    return position;
}

TrackSegment _track(const json& track) {
    TrackSegment segment;
    segment.startXMm = track.at("x0").get<double>();
    segment.startYMm = track.at("y0").get<double>();
    segment.endXMm = track.at("x1").get<double>();
    segment.endYMm = track.at("y1").get<double>();
    segment.widthMm = track.at("w").get<double>();
    segment.copperLayerName = track.at("layer").get<std::string>();
    segment.uuid = track.at("uuid").get<std::string>();
    return segment;
}

/// _findFootprintPad(): the footprint by reference, then its pad by number, falling back to a pin
/// function name.
const json* _findPad(const json& summary, const std::string& footprintRef, const std::string& pin, std::string& error) {
    for (const json& footprint : summary.at("footprints")) {
        if (footprint.at("ref").get<std::string>() != footprintRef) continue;
        for (const json& pad : footprint.at("pads")) {
            if (pad.at("num").get<std::string>() == pin) return &pad;
        }
        for (const json& pad : footprint.at("pads")) {
            if (pad.at("fn").get<std::string>() == pin) return &pad;
        }
        error = "pad/pin not found: " + footprintRef + "." + pin;
        return nullptr;
    }
    error = "footprint not found: " + footprintRef;
    return nullptr;
}

template <typename Result>
Result _failure(std::string error) {
    Result result;
    result.ok = false;
    result.error = std::move(error);
    return result;
}

/// Runs `body` against the board summary, translating a JSON surprise into an error result.
template <typename Result, typename Body>
Result _withSummary(BoardState& state, Body body) {
    std::lock_guard lock(state.mutex);
    std::string error;
    const json* summary = _summary(state, error);
    if (!summary) return _failure<Result>(std::move(error));
    try {
        Result result = body(*summary);
        result.ok = true;
        return result;
    } catch (const json::exception& exception) {
        return _failure<Result>(std::string("Unexpected data from libkicad's KiCad bridge: ") + exception.what());
    }
}

