RuntimeState* createRuntimeRaw(std::string& error) {
    auto runtime = std::make_unique<RuntimeState>();
    if (!_findKicad(*runtime, error)) return nullptr;

    // A private directory for the bridge script and its results, removed with the runtime.
    std::random_device random;
    std::error_code fsError;
    const fs::path temporary = fs::temp_directory_path(fsError);
    if (fsError) {
        error = "No temporary directory for libkicad: " + fsError.message();
        return nullptr;
    }
    for (int attempt = 0; attempt < 16 && runtime->workDirectory.empty(); ++attempt) {
        const fs::path candidate = temporary / ("libkicad-" + std::to_string(random()));
        if (fs::create_directory(candidate, fsError)) runtime->workDirectory = candidate;
    }
    if (runtime->workDirectory.empty()) {
        error = "Could not create a temporary directory for libkicad";
        return nullptr;
    }
    runtime->script = runtime->workDirectory / "kicad_bridge.py";
    std::ofstream script(runtime->script, std::ios::binary);
    script.write(reinterpret_cast<const char*>(kKicadBridgeScript), static_cast<std::streamsize>(kKicadBridgeScriptSize));
    if (!script) {
        error = "Could not write libkicad's KiCad bridge to " + _utf8(runtime->script);
        return nullptr;
    }
    return runtime.release();
}

void destroyRuntimeRaw(RuntimeState* runtime) {
    if (!runtime) return;
    std::error_code ignored;
    fs::remove_all(runtime->workDirectory, ignored);
    delete runtime;
}

BoardState* createBoardRaw(RuntimeState& runtime, std::string projectPath, std::string boardPath) {
    auto state = std::make_unique<BoardState>(runtime, std::move(projectPath), std::move(boardPath));
    // Like libkicad.cpp, load eagerly (a query is imminent) but defer any error to the first query.
    std::lock_guard lock(state->mutex);
    std::string ignored;
    (void)_summary(*state, ignored);
    return state.release();
}

void destroyBoardRaw(BoardState* state) {
    delete state;
}

RawPadCountsResult countPadsRaw(BoardState& state) {
    return _withSummary<RawPadCountsResult>(state, [](const json& summary) {
        const json& counts = summary.at("counts");
        RawPadCountsResult result;
        result.counts.footprintCount = counts.at("footprints").get<std::int32_t>();
        result.counts.trackCount = counts.at("tracks").get<std::int32_t>();
        result.counts.zoneCount = counts.at("zones").get<std::int32_t>();
        result.counts.padCount = counts.at("pads").get<std::int32_t>();
        return result;
    });
}

RawNetNameResult netForFootprintPinRaw(BoardState& state, const std::string& footprintRef, const std::string& pin) {
    std::string findError;
    RawNetNameResult result = _withSummary<RawNetNameResult>(state, [&](const json& summary) {
        RawNetNameResult found;
        if (const json* pad = _findPad(summary, footprintRef, pin, findError)) found.netName = pad->at("net").get<std::string>();
        return found;
    });
    return result.ok && !findError.empty() ? _failure<RawNetNameResult>(findError) : result;
}

RawNetNameResult netClassForNetRaw(BoardState& state, const std::string& netName) {
    bool exists = false;
    RawNetNameResult result = _withSummary<RawNetNameResult>(state, [&](const json& summary) {
        RawNetNameResult found;
        const json& constituents = summary.at("netConstituents");
        if (auto it = constituents.find(netName); it != constituents.end()) {
            exists = true;
            if (!it->empty()) found.netName = it->front().get<std::string>();
        }
        return found;
    });
    if (result.ok && !exists) return _failure<RawNetNameResult>("No net named \"" + netName + "\" exists on the board");
    return result;
}

RawPadResult resolvePinRaw(BoardState& state, const std::string& footprintRef, const std::string& pin) {
    std::string findError;
    RawPadResult result = _withSummary<RawPadResult>(state, [&](const json& summary) {
        RawPadResult found;
        if (const json* pad = _findPad(summary, footprintRef, pin, findError)) found.pad = _padPosition(*pad, footprintRef);
        return found;
    });
    return result.ok && !findError.empty() ? _failure<RawPadResult>(findError) : result;
}

RawNetClassMembersResult netsInNetClassRaw(BoardState& state, const std::string& netClassName) {
    return _withSummary<RawNetClassMembersResult>(state, [&](const json& summary) {
        RawNetClassMembersResult result;
        const json& constituents = summary.at("netConstituents");
        for (const json& net : summary.at("nets")) {
            const std::string name = net.get<std::string>();
            const json& classes = constituents.at(name);
            if (std::any_of(classes.begin(), classes.end(), [&](const json& c) { return c.get<std::string>() == netClassName; })) {
                result.netNames.push_back(name);
            }
        }
        return result;
    });
}

RawPadsOnNetResult padsOnNetRaw(BoardState& state, const std::string& netName) {
    return _withSummary<RawPadsOnNetResult>(state, [&](const json& summary) {
        RawPadsOnNetResult result;
        for (const json& footprint : summary.at("footprints")) {
            const std::string reference = footprint.at("ref").get<std::string>();
            for (const json& pad : footprint.at("pads")) {
                if (pad.at("net").get<std::string>() == netName) result.pads.push_back(_padPosition(pad, reference));
            }
        }
        return result;
    });
}

RawTracksOnNetResult tracksOnNetRaw(BoardState& state, const std::string& netName) {
    return _withSummary<RawTracksOnNetResult>(state, [&](const json& summary) {
        RawTracksOnNetResult result;
        for (const json& track : summary.at("tracks")) {
            // Straight segments only: see libkicad.cpp's tracksOnNetRaw().
            if (!track.at("arc").get<bool>() && track.at("net").get<std::string>() == netName) {
                result.tracks.push_back(_track(track));
            }
        }
        return result;
    });
}

RawPadsOnNetResult allPadsRaw(BoardState& state) {
    return _withSummary<RawPadsOnNetResult>(state, [](const json& summary) {
        RawPadsOnNetResult result;
        for (const json& footprint : summary.at("footprints")) {
            const std::string reference = footprint.at("ref").get<std::string>();
            for (const json& pad : footprint.at("pads")) result.pads.push_back(_padPosition(pad, reference));
        }
        return result;
    });
}

RawAllTracksResult allTracksRaw(BoardState& state) {
    return _withSummary<RawAllTracksResult>(state, [](const json& summary) {
        RawAllTracksResult result;
        for (const json& track : summary.at("tracks")) {
            result.tracks.emplace_back(track.at("net").get<std::string>(), _track(track));
        }
        return result;
    });
}

RawZonesResult zonesRaw(BoardState& state) {
    return _withSummary<RawZonesResult>(state, [](const json& summary) {
        RawZonesResult result;
        for (const json& zone : summary.at("zones")) {
            ZoneInfo info;
            info.netName = zone.at("net").get<std::string>();
            info.copperLayerName = zone.at("layer").get<std::string>();
            const json& points = zone.at("outline");
            for (std::size_t i = 0; i + 1 < points.size(); i += 2) {
                info.outlineMm.emplace_back(points[i].get<double>(), points[i + 1].get<double>());
            }
            result.zones.push_back(std::move(info));
        }
        return result;
    });
}

RawBoardGeometryResult boardGeometryRaw(BoardState& state) {
    std::lock_guard lock(state.mutex);
    std::string error;
    if (!_refresh(state, error)) return _failure<RawBoardGeometryResult>(std::move(error));
    if (!state.geometry) {
        std::optional<json> geometry = _bridge(state.runtime, _boardArguments(state, "geometry"), error);
        if (!geometry) return _failure<RawBoardGeometryResult>(std::move(error));
        state.geometry = std::move(*geometry);
    }
    try {
        const json& geometry = *state.geometry;
        RawBoardGeometryResult result;
        result.ok = true;
        result.geometry.outline = _loops(geometry.at("outline"));
        result.geometry.copper = _copper(geometry.at("copper"));
        result.geometry.frontMaskOpenings = _loops(geometry.at("frontMask"));
        result.geometry.backMaskOpenings = _loops(geometry.at("backMask"));
        for (const auto& [key, destination] : {std::pair{"frontSilk", &result.geometry.frontSilkscreen},
                                              std::pair{"backSilk", &result.geometry.backSilkscreen}}) {
            for (const json& entry : geometry.at(key)) {
                destination->push_back(SilkscreenPolygon{entry.at(0).get<std::string>(),
                                                         _loop(json::array({entry.at(1), entry.at(2)}))});
            }
        }
        return result;
    } catch (const json::exception& exception) {
        return _failure<RawBoardGeometryResult>(std::string("Unexpected data from libkicad's KiCad bridge: ") + exception.what());
    }
}

RawBoardLayersResult boardLayersRaw(BoardState& state) {
    return _withSummary<RawBoardLayersResult>(state, [](const json& summary) {
        RawBoardLayersResult result;
        for (const json& layer : summary.at("layers")) result.layers.push_back(_layerInfo(layer));
        return result;
    });
}

RawBoardLayerGeometryResult boardLayerGeometryRaw(BoardState& state, const std::string& layerName) {
    std::lock_guard lock(state.mutex);
    std::string error;
    if (!_refresh(state, error)) return _failure<RawBoardLayerGeometryResult>(std::move(error));
    auto cached = state.layers.find(layerName);
    if (cached == state.layers.end()) {
        std::vector<std::string> arguments = _boardArguments(state, "layer");
        arguments.push_back("--layer");
        arguments.push_back(layerName);
        std::optional<json> layer = _bridge(state.runtime, std::move(arguments), error);
        if (!layer) return _failure<RawBoardLayerGeometryResult>(std::move(error));
        cached = state.layers.emplace(layerName, std::move(*layer)).first;
    }
    try {
        const json& layer = cached->second;
        RawBoardLayerGeometryResult result;
        result.ok = true;
        result.geometry.layer = _layerInfo(layer.at("layer"));
        result.geometry.copper = _copper(layer.at("copper"));
        result.geometry.contours = _loops(layer.at("contours"));
        result.geometry.boardOutline = _loops(layer.at("boardOutline"));
        return result;
    } catch (const json::exception& exception) {
        return _failure<RawBoardLayerGeometryResult>(std::string("Unexpected data from libkicad's KiCad bridge: ") +
                                                     exception.what());
    }
}

