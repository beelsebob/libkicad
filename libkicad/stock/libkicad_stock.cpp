RawComponentSimModelsResult componentSimModelsRaw(BoardState& state) {
    std::lock_guard lock(state.mutex);
    RawComponentSimModelsResult result;
    const json* summary = _summary(state, result.error);
    if (!summary) return result;
    // Not cached: the models come from the schematic, which changes independently of the board.
    std::optional<json> schematic =
            _bridge(state.runtime, {"simmodels", "--project", state.projectPath}, result.error);
    if (!schematic) return result;

    try {
        const json& subcircuits = schematic->at("subcircuits");
        const SubcircuitLookup lookup = [&subcircuits](const std::string& name) -> std::optional<std::string> {
            std::string key = name;
            std::transform(key.begin(), key.end(), key.begin(), [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
            if (auto it = subcircuits.find(key); it != subcircuits.end()) return it->get<std::string>();
            return std::nullopt;
        };
        static const std::map<std::string, ComponentSimModelStatus> statuses = {
            {"resolved", ComponentSimModelStatus::Resolved}, {"excluded", ComponentSimModelStatus::ExcludedFromSimulation},
            {"nomodel", ComponentSimModelStatus::NoModel}, {"error", ComponentSimModelStatus::Error}};

        std::map<std::string, ComponentSimModel> byReference;
        for (const json& entry : schematic->at("models")) {
            ComponentSimModel model;
            model.reference = entry.at("reference").get<std::string>();
            model.status = statuses.at(entry.at("status").get<std::string>());
            model.deviceType = entry.at("deviceType").get<std::string>();
            model.modelName = entry.at("modelName").get<std::string>();
            model.libraryPath = entry.at("libraryPath").get<std::string>();
            model.message = entry.at("message").get<std::string>();
            for (const json& raw : entry.at("elements")) {
                ComponentSimElement element;
                element.kind = raw.at("kind").get<std::string>().front();
                element.name = raw.at("name").get<std::string>();
                element.value = raw.at("value").get<std::string>();
                for (const json& node : raw.at("nodes")) {
                    const std::string kind = node.at(0).get<std::string>();
                    element.nodes.push_back(ComponentSimNode{kind == "pin" ? ComponentSimNode::Kind::Pin
                                                             : kind == "ground" ? ComponentSimNode::Kind::Ground
                                                                                : ComponentSimNode::Kind::Internal,
                                                             node.at(1).get<std::string>()});
                }
                if (element.kind == 'X' && raw.contains("subckt")) {
                    // Expanded with the same code as the source backend's eeschema path.
                    const std::string name = raw.at("subckt").get<std::string>();
                    const std::optional<std::string> code = lookup(name);
                    if (!code) {
                        model.status = ComponentSimModelStatus::Error;
                        model.message = "Subcircuit \"" + name + "\" was not found in the model's library";
                        break;
                    }
                    SpiceParameters parameters;
                    for (const auto& [parameter, value] : raw.at("params").items()) {
                        if (auto number = evaluateSpiceExpression(value.get<std::string>(), parameters)) {
                            parameters[parameter] = *number;
                        }
                    }
                    std::string expandError;
                    std::optional<std::vector<ComponentSimElement>> expanded =
                            expandSubcircuit(*code, model.reference, element.nodes, lookup, expandError, parameters);
                    if (!expanded) {
                        model.status = ComponentSimModelStatus::Error;
                        model.message = expandError;
                        break;
                    }
                    model.elements.insert(model.elements.end(), expanded->begin(), expanded->end());
                    continue;
                }
                if (element.kind == 'R' || element.kind == 'C' || element.kind == 'L') {
                    element.numericValue = evaluateElementValue(element.kind, element.value, {});
                }
                model.elements.push_back(std::move(element));
            }
            if (model.status == ComponentSimModelStatus::Error) model.elements.clear();
            byReference.emplace(model.reference, std::move(model));
        }

        // One entry per board footprint, as libkicad.cpp's componentSimModelsRaw().
        for (const json& footprint : summary->at("footprints")) {
            const std::string reference = footprint.at("ref").get<std::string>();
            if (auto it = byReference.find(reference); it != byReference.end()) {
                result.models.push_back(it->second);
            } else {
                ComponentSimModel model;
                model.reference = reference;
                model.status = ComponentSimModelStatus::NoSymbol;
                result.models.push_back(std::move(model));
            }
        }
        result.ok = true;
    } catch (const json::exception& exception) {
        result.error = std::string("Unexpected data from libkicad's KiCad bridge: ") + exception.what();
    }
    return result;
}

RawUnsavedAutosavesResult unsavedAutosavesRaw(BoardState& state) {
    RawUnsavedAutosavesResult result;
    {
        std::lock_guard lock(state.mutex);
        if (!_refresh(state, result.error)) return result;
    }
    // KiCad's default (project-directory) autosave location: "_autosave-<name>" beside <name>, in
    // the project directory and its subdirectories other than .history and *-backups. Mirrors
    // LOCAL_HISTORY::CollectAutosaveFilePairs() and libkicad.cpp's staleness test.
    static constexpr std::string_view kPrefix = "_autosave-";
    const fs::path projectDirectory = _fromUtf8(state.projectPath).parent_path();
    std::error_code error;
    fs::recursive_directory_iterator it(projectDirectory, fs::directory_options::skip_permission_denied, error);
    for (; !error && it != fs::recursive_directory_iterator(); it.increment(error)) {
        const std::string name = _utf8(it->path().filename());
        if (it->is_directory(error)) {
            if (name == ".history" || (name.size() >= 8 && name.ends_with("-backups"))) it.disable_recursion_pending();
            continue;
        }
        if (!name.starts_with(kPrefix)) continue;
        const fs::path autosave = it->path();
        const fs::path source = autosave.parent_path() / _fromUtf8(name.substr(kPrefix.size()));
        std::error_code ec;
        bool unsaved = !fs::exists(source, ec);
        if (!unsaved) {
            const auto autosaveTime = fs::last_write_time(autosave, ec);
            const auto sourceTime = ec ? autosaveTime : fs::last_write_time(source, ec);
            if (!ec && autosaveTime > sourceTime) {
                std::ifstream a(autosave, std::ios::binary), b(source, std::ios::binary);
                unsaved = !(a && b && std::equal(std::istreambuf_iterator<char>(a), std::istreambuf_iterator<char>(),
                                                 std::istreambuf_iterator<char>(b), std::istreambuf_iterator<char>()));
            }
        }
        if (unsaved) result.files.push_back({_utf8(autosave), _utf8(source)});
    }
    result.ok = true;
    return result;
}

