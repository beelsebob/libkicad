// libkicad's "stock" backend: the detail:: functions libkicad_api.cpp calls (libkicad_result.hpp),
// implemented on top of an installed KiCad rather than KiCad's C++ internals. Board data comes
// from kicad_bridge.py, run with the KiCad install's own Python, and simulation models from
// kicad-cli's netlists, so no KiCad source build is needed. libkicad_api.cpp and the public API
// in libkicad.hpp are shared with the source backend (libkicad.cpp) unchanged.
//
// Each Board caches the bridge's answers until its board or project file changes, as
// libkicad.cpp's _loadBoard() does with the loaded BOARD.

