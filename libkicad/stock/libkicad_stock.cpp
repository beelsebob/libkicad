struct RuntimeState {
    fs::path python;
    fs::path kicadCli;
    fs::path workDirectory;
    fs::path script;
    std::atomic<unsigned> counter{0};
};

struct BoardState {
    BoardState(RuntimeState& aRuntime, std::string aProjectPath, std::string aBoardPath)
            : runtime(aRuntime), projectPath(std::move(aProjectPath)), boardPath(std::move(aBoardPath)) {}

    RuntimeState& runtime;
    std::string projectPath;
    std::string boardPath;
    // Everything below is guarded by `mutex`.
    std::mutex mutex;
    fs::file_time_type projectMTime;
    fs::file_time_type boardMTime;
    std::optional<json> summary;
    std::optional<json> geometry;
    std::map<std::string, json> layers;
};

